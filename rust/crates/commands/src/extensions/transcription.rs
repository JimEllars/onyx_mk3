use async_trait::async_trait;
use runtime::api_specs::webhook_payload::AximWebhookPayload;
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};

use crate::actions::axim_core_relay::AximCoreRelayAction;
use crate::actions::persistence_manager::PersistenceManager;

use crate::micro_program::MicroProgram;

#[derive(Debug, Serialize, Deserialize, Default)]
pub struct TranscriptionRequest {
    #[serde(default)]
    pub audio_url: Option<String>,
    #[serde(default)]
    pub language: Option<String>,
}

#[derive(Debug, Serialize, Deserialize)]
pub struct TranscriptionResponse {
    pub status: String,
    pub transcript: Option<String>,
    pub warnings: crate::extensions::WarningMetadata,
}

#[derive(Debug)]
pub struct NootaTranscription;

#[async_trait]
impl MicroProgram for NootaTranscription {
    fn name(&self) -> &'static str {
        "Noota Audio Transcription"
    }

    fn signature(&self) -> &'static str {
        "transcribe_audio"
    }

    async fn check_idempotency(
        &self,
        _payload: &AximWebhookPayload,
    ) -> Result<Option<Value>, String> {
        Ok(None)
    }

    async fn execute_internal(&self, payload: &AximWebhookPayload) -> Result<Value, String> {
        let req: TranscriptionRequest =
            serde_json::from_value(payload.meta_data.clone()).unwrap_or_default();

        let mut missing_fields = Vec::new();

        if req.audio_url.is_none() {
            missing_fields.push("audio_url".to_string());
        }

        let mut transcript = None;

        if missing_fields.is_empty() {
            let _url = req.audio_url.clone().unwrap();
            let _lang = req.language.clone().unwrap_or_else(|| "en".to_string());

            // Mock: send request to Noota API using reqwest
            let _client = reqwest::Client::new();
            let _endpoint = "https://api.noota.io/v1/transcribe";
            let _api_key =
                std::env::var("NOOTA_API_KEY").unwrap_or_else(|_| "mock_noota_key".to_string());

            println!("Mock: Requesting transcription from Noota for audio...");

            /*
            let request_payload = json!({
                "url": _url,
                "language": _lang
            });

            let _res = _client
                .post(_endpoint)
                .header("Authorization", format!("Bearer {}", _api_key))
                .json(&request_payload)
                .send()
                .await
                .map_err(|e| format!("Failed to call Noota API: {}", e))?;
            */

            transcript = Some("Mock transcript generated by Noota API...".to_string());
        }

        let status = if missing_fields.is_empty() {
            "Completed".to_string()
        } else {
            "Failed_Validation".to_string()
        };

        let res = TranscriptionResponse {
            status: status.clone(),
            transcript: transcript.clone(),
            warnings: crate::extensions::WarningMetadata { missing_fields },
        };

        if status == "Completed" {
            let payload_to_save = json!({
                "type": "transcription",
                "transcript": transcript,
                "audio_url": req.audio_url,
                "language": req.language,
            });
            let _ = PersistenceManager::dual_save(&payload_to_save).await;

            let relay_payload = json!({
                "generator": "transcription",
                "status": status,
                "transcript": transcript,
                "parameters": req,
            });
            let _ = AximCoreRelayAction::execute(&relay_payload).await;
        }

        Ok(json!(res))
    }
}
